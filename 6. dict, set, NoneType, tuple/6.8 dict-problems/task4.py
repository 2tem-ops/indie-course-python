# Азбука Морзе

morse = {'a': '•—', 'b': '—•••', 'c': '—•—•', 'd': '—••',
         'e': '•', 'f': '••—•', 'g': '——•', 'h': '••••',
         'i': '••', 'j': '•———', 'k': '—•—', 'l': '•—••',
         'm': '——', 'n': '—•', 'o': '———', 'p': '•——•',
         'q': '——•—', 'r': '•—•', 's': '•••', 't': '—',
         'u': '••—', 'v': '•••—', 'w': '•——', 'x': '—••—',
         'y': '—•——', 'z': '——••'}

s = input().lower().split()
res = []

for word in s:
    lst = []
    for char in word:
        if not char.isspace():
            lst.append(morse[char])
    res.append(lst)

print(*[" ".join(word) for word in res], sep="\n")